/**
 * Build script: generates firebase-messaging-sw.js with environment variables injected.
 * 
 * Service workers run outside the Next.js context and cannot access process.env.
 * This script reads from .env.local and writes the config into the SW file at build time.
 * 
 * Usage: node scripts/generate-firebase-sw.js
 * Runs automatically before every build via the "prebuild" npm script.
 */

const fs = require("fs");
const path = require("path");

// Load .env.local manually
function loadEnv() {
  const envPath = path.join(__dirname, "..", ".env.local");
  if (!fs.existsSync(envPath)) {
    console.warn("⚠️  .env.local not found, checking process.env (Vercel build)");
    return {};
  }
  const content = fs.readFileSync(envPath, "utf-8");
  const env = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const [key, ...rest] = trimmed.split("=");
    env[key.trim()] = rest.join("=").trim();
  }
  return env;
}

const localEnv = loadEnv();

// Use local env with fallback to process.env (for Vercel builds)
const get = (key) => localEnv[key] || process.env[key] || "";

const config = {
  apiKey: get("NEXT_PUBLIC_FIREBASE_API_KEY"),
  authDomain: get("NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN"),
  projectId: get("NEXT_PUBLIC_FIREBASE_PROJECT_ID"),
  storageBucket: get("NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET"),
  messagingSenderId: get("NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID"),
  appId: get("NEXT_PUBLIC_FIREBASE_APP_ID"),
};

// Validate that we have the required values
const missing = Object.entries(config).filter(([, v]) => !v);
if (missing.length > 0) {
  console.warn(`⚠️  Missing Firebase env vars: ${missing.map(([k]) => k).join(", ")}`);
  console.warn("   Service worker will be generated with empty values.");
  console.warn("   Push notifications will NOT work until these are set.");
}

const swContent = `/* eslint-disable no-undef */
// AUTO-GENERATED — Do not edit manually!
// Generated by scripts/generate-firebase-sw.js at build time.
// To update, change .env.local and run: npm run generate-sw

importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js");

firebase.initializeApp({
  apiKey: "${config.apiKey}",
  authDomain: "${config.authDomain}",
  projectId: "${config.projectId}",
  storageBucket: "${config.storageBucket}",
  messagingSenderId: "${config.messagingSenderId}",
  appId: "${config.appId}",
});

const messaging = firebase.messaging();

// Listen for SKIP_WAITING message from PWAUpdater component
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

// Handle background messages
messaging.onBackgroundMessage((payload) => {
  console.log("[SW] Background message received:", payload);

  const notificationTitle = payload.notification?.title || "FastSwype";
  const notificationOptions = {
    body: payload.notification?.body || "You have a new notification",
    icon: "/icons/icon-192x192.png",
    badge: "/icons/icon-72x72.png",
    tag: payload.data?.tag || "fastswype-notification",
    data: {
      link: payload.data?.link || "/proposals",
    },
    vibrate: [200, 100, 200],
    actions: [
      {
        action: "open",
        title: "View",
      },
    ],
  };

  self.registration.showNotification(notificationTitle, notificationOptions);
});

// Handle notification click
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const link = event.notification.data?.link || "/proposals";

  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if (client.url.includes(self.location.origin)) {
          client.navigate(link);
          return client.focus();
        }
      }
      return clients.openWindow(link);
    })
  );
});
`;

const outputPath = path.join(__dirname, "..", "public", "firebase-messaging-sw.js");
fs.writeFileSync(outputPath, swContent, "utf-8");
console.log("✅ Generated public/firebase-messaging-sw.js with env variables injected");
